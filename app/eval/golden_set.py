def get_categories() -> dict[str, int]:
    counter: dict[str, int] = {}
    for case in GOLDEN_SET:
        counter[case.category] = counter.get(case.category, 0) + 1
    return counter


def get_image_cases() -> list[EvalCase]:
    return [case for case in GOLDEN_SET if case.needs_image]
